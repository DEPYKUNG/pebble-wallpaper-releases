"""Offline adapter for the pinned upstream renderer; no packaging side effects on import."""
from base64 import b64encode
import hashlib
import json
import re


class RendererBuildError(ValueError):
    """A reviewed upstream/bridge contract no longer matches."""


def replace_once(text, before, after, name):
    count = text.count(before)
    if not before or count != 1:
        raise RendererBuildError(f'Renderer patch {name!r}: expected 1 anchor, found {count}. '
                                 'Review the upstream adapter before building.')
    return text.replace(before, after, 1)


def apply_patches(script, patches):
    names = set()
    for patch in patches:
        name = patch['name']
        if not name or name in names:
            raise RendererBuildError(f'Duplicate or empty renderer patch name: {name!r}')
        names.add(name)
        script = replace_once(script, patch['before'], patch['after'], name)
    return script


def read_upstream(work, manifest):
    sources = {}
    for name in ('original.js', 'original.html'):
        data = (work / name).read_bytes()
        actual = hashlib.sha256(data).hexdigest()
        if actual != manifest['files'][name]:
            raise RendererBuildError(f'Upstream {name} SHA256 mismatch ({actual}). '
                                     'Review patches, textures and bridge compatibility; '
                                     'do not update the fingerprint alone.')
        sources[name] = data.decode('utf-8')
    return sources


def texture_table(script):
    matches = list(re.finditer(r'Sg=\{([^}]*)\},Mo=Object\.keys\(Sg\)', script))
    if len(matches) != 1:
        raise RendererBuildError(f'Texture dictionary: expected 1, found {len(matches)}')
    table = matches[0].group(1)
    pairs = re.findall(r'(\w+):"([^"]*)"', table)
    # Require full consumption, unique keys and multiple textures, not a partial match.
    if (len(pairs) < 2 or len({key for key, _ in pairs}) != len(pairs)
            or ','.join(f'{key}:"{label}"' for key, label in pairs) != table):
        raise RendererBuildError('Texture dictionary is incomplete or contains duplicate keys')
    return pairs


def build_renderer(work, generated, resources):
    """Validate and assemble first; only then write the three generated build files."""
    adapter = work / 'renderer'
    manifest = json.loads((adapter / 'upstream.json').read_text())
    sources = read_upstream(work, manifest)
    script, html = sources['original.js'], sources['original.html']
    if '</script' in script.lower():
        raise RendererBuildError('Upstream JS cannot safely be embedded in a script element')
    texture_pairs = texture_table(script)
    colors = json.loads((adapter / 'colors.json').read_text())
    script = apply_patches(script, json.loads((adapter / 'patches.json').read_text()))
    script += ('\nconst pebbleTextures = ' + json.dumps([key for key, _ in texture_pairs])
               + ';\nconst pebbleFamilies = '
               + json.dumps({key: spec for key, _, spec in colors}) + ';\n'
               + (adapter / 'bridge.js').read_text())
    for name in manifest['native_api']:
        if len(re.findall(r'window\.' + re.escape(name) + r'\s*=', script)) != 1:
            raise RendererBuildError(f'Native renderer API {name!r} must be assigned exactly once')
    if '</script' in script.lower():
        raise RendererBuildError('Bridge JS cannot safely be embedded in a script element')
    html, count = re.subn(r'<script[^>]+src="[^"]+"[^>]*></script>', '', html)
    if count != 1:
        raise RendererBuildError(f'Upstream module script: expected 1, found {count}')
    policy = "default-src 'none'; img-src data:; script-src 'unsafe-inline'; style-src 'unsafe-inline';"
    html = replace_once(html, '<head>', f'<head><meta http-equiv="Content-Security-Policy" content="{policy}">', 'html-csp')
    html = replace_once(html, '</head>', '<style>' + (adapter / 'wallpaper.css').read_text()
                        + '    </style></head>', 'html-style')
    body = (adapter / 'body.html').read_text()
    # Substitute the script last so user JS is never treated as a template.
    for token, asset in (('PASS_CARD', 'pass-card.png'), ('QUESTION', 'desktop-question.png')):
        encoded = b64encode((work / asset).read_bytes()).decode('ascii')
        expected = 2 if token == 'QUESTION' else 1
        if body.count('@@' + token + '@@') != expected:
            raise RendererBuildError(f'Body template {token}: expected {expected} placeholders')
        body = body.replace('@@' + token + '@@', encoded)
    body = replace_once(body, '@@SCRIPT@@', script, 'html-script')
    html = replace_once(html, '</body>', body, 'html-body')
    texture_header = (
        '// Generated by package.py from the renderer bundle. Do not edit.\n'
        f'#define PebbleTextureCount {len(texture_pairs)}\n'
        'static const char *const PebbleTextureKeys[] = {'
        + ', '.join(f'"{key}"' for key, _ in texture_pairs) + '};\n'
        'static const char *const PebbleTextureLabels[] = {'
        + ', '.join(f'"{label}"' for _, label in texture_pairs) + '};\n')
    color_header = (
        '// Generated by package.py. Keep the menu and the renderer on one table.\n'
        f'#define PebbleColorCount {len(colors)}\n'
        'static const char *const PebbleColorKeys[] = {'
        + ', '.join(f'"{key}"' for key, _, _ in colors) + '};\n'
        'static const char *const PebbleColorLabels[] = {'
        + ', '.join(f'"{label}"' for _, label, _ in colors) + '};\n')
    (generated / 'PebbleTextures.h').write_text(texture_header)
    (generated / 'PebbleColors.h').write_text(color_header)
    (resources / 'wallpaper.html').write_text(html)
